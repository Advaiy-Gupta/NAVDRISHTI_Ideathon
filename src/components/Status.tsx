import type { CitizenVerification, ComplaintStatus, StatusSource } from '../data/types';

const STATUS_TONE: Record<ComplaintStatus, string> = {
  Submitted: 'text-muted border-line',
  Acknowledged: 'text-accent border-accent/40',
  'In Progress': 'text-accent border-accent/40',
  'Action Reported': 'text-warn border-warn/40',
  Resolved: 'text-ok border-ok/40',
  Reopened: 'text-crit border-crit/40',
  Overdue: 'text-crit border-crit/40',
};

const STATUS_DOT: Record<ComplaintStatus, string> = {
  Submitted: 'bg-muted',
  Acknowledged: 'bg-accent',
  'In Progress': 'bg-accent',
  'Action Reported': 'bg-warn',
  Resolved: 'bg-ok',
  Reopened: 'bg-crit',
  Overdue: 'bg-crit',
};

export function StatusLabel({ status }: { status: ComplaintStatus }) {
  return (
    <span className={`inline-flex items-center gap-1.5 whitespace-nowrap rounded-sm border px-1.5 py-0.5 text-xs font-medium ${STATUS_TONE[status]}`}>
      <span className={`h-1.5 w-1.5 rounded-full ${STATUS_DOT[status]}`} aria-hidden />
      {status}
    </span>
  );
}

export const SOURCE_LABEL: Record<StatusSource, string> = {
  official: 'Official portal (sample)',
  user: 'Reported by you',
  demo: 'Simulated demo',
};

const SOURCE_DESC: Record<StatusSource, string> = {
  official: 'Status as recorded on the official portal. In this prototype these are sample records, not live portal data.',
  user: 'Information you entered yourself. It has not been confirmed by the department.',
  demo: 'Generated by the prototype demo path. Nothing was sent to any government system.',
};

export function SourceLabel({ source }: { source: StatusSource }) {
  const style =
    source === 'official'
      ? 'text-ink'
      : source === 'user'
        ? 'text-accent'
        : 'text-warn';
  return (
    <span title={SOURCE_DESC[source]} className={`text-xs ${style}`}>
      {source === 'demo' ? <span className="font-medium">{SOURCE_LABEL[source]}</span> : SOURCE_LABEL[source]}
    </span>
  );
}

export const VERIFICATION_LABEL: Record<CitizenVerification, string> = {
  'not-requested': 'Not applicable yet',
  pending: 'Awaiting your confirmation',
  confirmed: 'Confirmed by citizen',
  disputed: 'Disputed by citizen',
};

export function VerificationLabel({ value }: { value: CitizenVerification }) {
  const tone =
    value === 'confirmed' ? 'text-ok' : value === 'disputed' ? 'text-crit' : value === 'pending' ? 'text-warn' : 'text-muted';
  return <span className={`text-xs ${tone}`}>{VERIFICATION_LABEL[value]}</span>;
}

export function SourceLegend() {
  return (
    <dl className="grid grid-cols-1 gap-3 text-xs text-muted sm:grid-cols-3">
      {(Object.keys(SOURCE_LABEL) as StatusSource[]).map((s) => (
        <div key={s}>
          <dt>
            <SourceLabel source={s} />
          </dt>
          <dd className="mt-0.5">{SOURCE_DESC[s]}</dd>
        </div>
      ))}
    </dl>
  );
}
